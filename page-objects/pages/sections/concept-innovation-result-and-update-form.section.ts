import { Locator, Page } from '@playwright/test';

export class ConceptInnovationResultAndUpdateFormSection {
  readonly page: Page;
  readonly root: Locator;
  readonly form: Locator;
  readonly newProductConceptButton: Locator;
  readonly generationContainer: Locator;
  readonly briefContainer: Locator;
  readonly productNameHeading: Locator;
  readonly productDetailHeading: Locator;
  readonly updatedNameHeading: Locator;
  readonly variationsHeading: Locator;
  readonly introText: Locator;
  readonly descriptionText: Locator;
  readonly tasteAppealText: Locator;
  readonly variationOneTitle: Locator;
  readonly variationOneDescription: Locator;
  readonly variationTwoTitle: Locator;
  readonly variationTwoDescription: Locator;
  readonly variationThreeTitle: Locator;
  readonly variationThreeDescription: Locator;
  readonly benefitsHeading: Locator;
  readonly benefitsBullets: Locator;
  readonly imageContainer: Locator;
  readonly productImage: Locator;
  readonly productImageDownloadButton: Locator;
  readonly downloadImageTooltip: Locator;
  readonly updateButton: Locator;
  readonly feedback: Locator;
  readonly loadingAnimation: Locator;
  readonly loadingImagesAnimation: Locator;
  readonly supportingInsightsLoading: Locator;
  readonly supportingInsightsAccordionButton: Locator;
  readonly supportingInsightsSection: Locator;
  readonly supportingInsightsLinks: Locator;
  readonly dvfEvaluationAccordionButton: Locator;
  readonly dvfEvaluationSection: Locator;
  readonly dvfSectionInfo: Locator;

  constructor(page: Page) {
    this.page = page;
    this.root = this.page.getByRole('main');
    this.form = this.root.locator('form').last();
    this.newProductConceptButton = this.page.getByRole('button', { name: 'New Product Concept' });
    this.generationContainer = this.root.locator('ul>li');
    this.briefContainer = this.generationContainer
      .locator('section')
      .filter({ has: this.page.getByRole('heading', { level: 4, name: 'Product Details' }) })
      .last()
      .locator('..');
    this.productNameHeading = this.generationContainer.getByRole('heading', { level: 3 });
    this.updatedNameHeading = this.generationContainer.getByRole('heading', { level: 3 }).nth(1);
    this.productDetailHeading = this.generationContainer
      .getByRole('heading', { level: 4 })
      .getByText('Product Details');
    this.introText = this.generationContainer.getByText('Intro', { exact: true });
    this.descriptionText = this.generationContainer.getByText('Description', { exact: true });
    this.tasteAppealText = this.generationContainer.getByText('Taste Appeal', { exact: true });
    this.variationsHeading = this.generationContainer.getByRole('heading', { level: 4 }).getByText('Variations');
    this.variationOneTitle = this.variationsHeading.locator(' ~ div.space-y-1 > p').nth(0);
    this.variationOneDescription = this.variationsHeading.locator(' ~ div.space-y-1 > p').nth(1);
    this.variationTwoTitle = this.variationsHeading.locator(' ~ div.space-y-1 > p').nth(2);
    this.variationTwoDescription = this.variationsHeading.locator(' ~ div.space-y-1 > p').nth(3);
    this.variationThreeTitle = this.variationsHeading.locator(' ~ div.space-y-1 > p').nth(4);
    this.variationThreeDescription = this.variationsHeading.locator(' ~ div.space-y-1 > p').nth(5);
    this.benefitsHeading = this.generationContainer.getByRole('heading', { level: 4 }).getByText('Product Benefits');
    this.benefitsBullets = this.benefitsHeading.locator('+ ul.space-y-1');
    this.imageContainer = this.generationContainer
      .getByRole('link')
      .filter({ has: this.page.getByAltText('product interpretation generated by AI') })
      .locator('..');
    this.productImage = this.generationContainer.getByAltText('product interpretation generated by AI');
    this.productImageDownloadButton = this.generationContainer.getByRole('button', { name: 'Download' });
    this.downloadImageTooltip = this.generationContainer.getByRole('tooltip', { name: 'Download' });
    this.updateButton = this.form.locator('button').getByText('Update');
    this.feedback = this.root.locator('label').getByText('Feedback');
    this.loadingAnimation = this.root.getByText('Generation in progress...');
    this.loadingImagesAnimation = this.root.getByText('Images Generation in progress');
    this.supportingInsightsAccordionButton = this.generationContainer.getByRole('heading', {
      name: 'Supporting Insights',
    });
    this.supportingInsightsLoading = this.generationContainer.getByRole('progressbar', {
      name: 'Generating Supporting Insights',
    });
    this.supportingInsightsSection = this.generationContainer.getByLabel('Supporting Insights');
    this.supportingInsightsLinks = this.supportingInsightsSection.getByRole('link');
    this.dvfEvaluationAccordionButton = this.generationContainer.getByRole('heading', { name: 'DVF Evaluation' });
    this.dvfEvaluationSection = this.dvfEvaluationAccordionButton.locator(' + [data-state="open"]');
    this.dvfSectionInfo = this.dvfEvaluationSection.getByRole('alert');
  }

  get dvfSectionScore(): Locator {
    const scoreRegex = /^Desirability:\s*\d.*Feasibility:\s*\d+/i;
    return this.dvfEvaluationSection.getByText(scoreRegex);
  }

  async pressUpdateButton(): Promise<void> {
    await this.updateButton.click();
  }
}
